-- Notas recibidas por evento (tarea/examen) que aún no tienen criterio donde aplicarse,
-- o que llegaron con el periodo CERRADO. Se conservan hasta que el docente actúe.
CREATE TABLE notas_pendientes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen        VARCHAR(10)   NOT NULL,
    origen_id     BIGINT        NOT NULL,
    titulo        VARCHAR(200),
    alumno_id     BIGINT,
    matricula_id  BIGINT        NOT NULL,
    seccion_id    BIGINT,
    curso_id      BIGINT        NOT NULL,
    periodo_id    BIGINT        NOT NULL,
    valor         NUMERIC(5,2)  NOT NULL,
    estado        VARCHAR(20)   NOT NULL DEFAULT 'PENDIENTE',
    fecha_evento  TIMESTAMP     NOT NULL DEFAULT now(),
    aplicada_en   TIMESTAMP,
    CONSTRAINT ck_np_origen CHECK (origen IN ('TAREA','EXAMEN')),
    CONSTRAINT ck_np_estado CHECK (estado IN ('PENDIENTE','PERIODO_CERRADO','APLICADA')),
    CONSTRAINT uk_np UNIQUE (matricula_id, origen, origen_id)
);
CREATE INDEX idx_np_curso ON notas_pendientes (seccion_id, curso_id, estado);
