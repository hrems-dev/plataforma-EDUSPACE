-- Alertas para administración (p. ej. matrícula sin tarifa configurada, cuotas parciales por decidir)
CREATE TABLE alertas_admin (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          VARCHAR(30)  NOT NULL,
    matricula_id  BIGINT,
    anio_id       BIGINT,
    nivel_id      BIGINT,
    grado_id      BIGINT,
    detalle       VARCHAR(400) NOT NULL,
    resuelta      BOOLEAN      NOT NULL DEFAULT FALSE,
    creada_en     TIMESTAMP    NOT NULL DEFAULT now(),
    resuelta_en   TIMESTAMP,
    CONSTRAINT ck_alerta_tipo CHECK (tipo IN ('SIN_TARIFA','CUOTA_PARCIAL','PERIODO_CERRADO','OTRA'))
);
CREATE INDEX idx_alerta_pend ON alertas_admin (resuelta, tipo);
