-- Materiales de curso: el docente sube archivos o enlaces para una sección y un curso; los ven los alumnos y apoderados de esa sección.
CREATE TABLE materiales (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio_id        BIGINT       NOT NULL,
    seccion_id     BIGINT       NOT NULL,
    curso_id       BIGINT       NOT NULL,
    docente_id     BIGINT       NOT NULL,
    titulo         VARCHAR(150) NOT NULL,
    descripcion    VARCHAR(1000),
    tipo           VARCHAR(8)   NOT NULL,                 -- ARCHIVO | ENLACE
    enlace         VARCHAR(500),
    nombre_archivo VARCHAR(200),
    ruta_storage   VARCHAR(400),
    content_type   VARCHAR(100),
    tamano_bytes   BIGINT,
    creado_en      TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_material_tipo CHECK (tipo IN ('ARCHIVO','ENLACE')),
    CONSTRAINT ck_material_contenido CHECK ((tipo = 'ENLACE' AND enlace IS NOT NULL) OR (tipo = 'ARCHIVO' AND ruta_storage IS NOT NULL))
);
CREATE INDEX idx_material_seccion_curso ON materiales (seccion_id, curso_id, creado_en DESC);
